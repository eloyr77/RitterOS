static void test_signatures(void)
{
    static const uint8_t e[] = { 1, 0, 1 };
    uint8_t bad[64];
    result("RSA-2048 PKCS #1 v1.5", rsa_verify_pkcs1(rsa2048_n, sizeof(rsa2048_n), e, 3, rsa2048_d, 32,
                                                     rsa2048_sig, sizeof(rsa2048_sig)));
    result("RSA-4096 PKCS #1 v1.5 (SHA-384)", rsa_verify_pkcs1(rsa4096_n, sizeof(rsa4096_n), e, 3, rsa4096_d, 48,
                                                              rsa4096_sig, sizeof(rsa4096_sig)));
    result("RSA-2048 PSS", rsa_verify_pss(rsa2048_n, sizeof(rsa2048_n), e, 3, rsa2048_d, 32, rsa2048pss_sig,
                                          sizeof(rsa2048pss_sig)));
    memcpy(bad, rsa2048_d, 32);
    bad[0] ^= 1;
    result("RSA: a wrong digest refused", !rsa_verify_pkcs1(rsa2048_n, sizeof(rsa2048_n), e, 3, bad, 32,
                                                            rsa2048_sig, sizeof(rsa2048_sig)));
    result("ECDSA P-256", ecdsa_verify(256, p256_pub, 65, p256_d, 32, p256_r, sizeof(p256_r), p256_s,
                                       sizeof(p256_s)));
    result("ECDSA P-384", ecdsa_verify(384, p384_pub, 97, p384_d, 48, p384_r, sizeof(p384_r), p384_s,
                                       sizeof(p384_s)));
    memcpy(bad, p256_d, 32);
    bad[31] ^= 1;
    uint8_t off[97];
    memcpy(off, p384_pub, 97);
    off[50] ^= 1;
    result("ECDSA: a wrong digest, a point off the curve refused",
           !ecdsa_verify(256, p256_pub, 65, bad, 32, p256_r, sizeof(p256_r), p256_s, sizeof(p256_s)) &&
           !ecdsa_verify(384, off, 97, p384_d, 48, p384_r, sizeof(p384_r), p384_s, sizeof(p384_s)));
}

#define RSA_THREADS 4
#define RSA_ROUNDS  60

/* (64h) Each thread checks the three RSA signatures RSA_ROUNDS times and
 * counts the answers that come out wrong (a good one refused, the wrong
 * digest taken). */
static int rsa_thread(void *arg)
{
    static const uint8_t e[] = { 1, 0, 1 };
    uint8_t bad[32];
    memcpy(bad, rsa2048_d, 32);
    bad[0] ^= 1;
    int wrong = 0;
    for (int i = 0; i < RSA_ROUNDS; i++) {
        wrong += !rsa_verify_pkcs1(rsa2048_n, sizeof(rsa2048_n), e, 3, rsa2048_d, 32, rsa2048_sig,
                                   sizeof(rsa2048_sig));
        wrong += !rsa_verify_pkcs1(rsa4096_n, sizeof(rsa4096_n), e, 3, rsa4096_d, 48, rsa4096_sig,
                                   sizeof(rsa4096_sig));
        wrong += !rsa_verify_pss(rsa2048_n, sizeof(rsa2048_n), e, 3, rsa2048_d, 32, rsa2048pss_sig,
                                 sizeof(rsa2048pss_sig));
        wrong += rsa_verify_pkcs1(rsa2048_n, sizeof(rsa2048_n), e, 3, bad, 32, rsa2048_sig,
                                  sizeof(rsa2048_sig));
    }
    *(int *)arg = wrong;
    return 0;
}

static void test_threads(void)
{
    thrd_t t[RSA_THREADS];
    int wrong[RSA_THREADS] = { 0 }, total = 0, started = 0;
    for (int i = 0; i < RSA_THREADS; i++)
        started += thrd_create(&t[i], rsa_thread, &wrong[i]) == thrd_success;
    for (int i = 0; i < started; i++) {
        thrd_join(t[i], 0);
        total += wrong[i];
    }
    printf("tlscrypto: RSA from %d threads at once: %d of %d answers wrong\n", started, total,
           started * RSA_ROUNDS * 4);
    result("RSA from several threads at once", started == RSA_THREADS && total == 0);
}

static void test_chain(void)
{
    struct x509 chain[2], roots[1], bad[2];
    result("certificates read", x509_parse(&chain[0], leaf_der, sizeof(leaf_der)) &&
                                x509_parse(&chain[1], int_der, sizeof(int_der)) &&
                                x509_parse(&roots[0], root_der, sizeof(root_der)));
    result("a chain to the root", x509_verify_chain(chain, 2, roots, 1, "test.local", made) == X509_OK);
    result("the wildcard, one label", x509_verify_chain(chain, 2, roots, 1, "a.example.test", made) == X509_OK &&
                                      x509_verify_chain(chain, 2, roots, 1, "b.a.example.test", made) == X509_ERR_NAME);
    result("another name refused", x509_verify_chain(chain, 2, roots, 1, "other.local", made) == X509_ERR_NAME);
    result("expired refused", x509_verify_chain(chain, 2, roots, 1, "test.local", made + 400LL * 86400) == X509_ERR_TIME);
    result("no root: untrusted", x509_verify_chain(chain, 2, roots, 0, "test.local", made) == X509_ERR_UNTRUSTED);
    leaf_der[sizeof(leaf_der) - 10] ^= 1;
    x509_parse(&bad[0], leaf_der, sizeof(leaf_der));
    bad[1] = chain[1];
    result("a tampered signature refused", x509_verify_chain(bad, 2, roots, 1, "test.local", made) == X509_ERR_SIGNATURE);
}

/* The system's root store (23e): how many of its certificates read, and
 * whether each one's own signature checks (the SHA-2 ones; a few old roots
 * sign themselves with SHA-1, which is not checked). */
static void test_roots(void)
{
    int fd = open("/system/certs/cacert.pem", O_RDONLY);
    if (fd < 0) {
        printf("tlscrypto: the system's roots: %s\n", strerror(errno));
        failures++;
        return;
    }
    static char pem[1 << 20];
    static uint8_t der[1 << 20];
    size_t size = 0;
    ssize_t k;
    while (size < sizeof(pem) && (k = read(fd, pem + size, sizeof(pem) - size)) > 0)
        size += (size_t)k;
    close(fd);
    const char *text = pem;
    size_t n, used = 0;
    int blocks = 0, read_ok = 0, sha2 = 0, signed_ok = 0;
    while ((n = pem_next(&text, pem + size, der + used, sizeof(der) - used))) {
        struct x509 c;
        blocks++;
        if (x509_parse(&c, der + used, n)) {
            read_ok++;
            if (c.sig_alg) {
                sha2++;
                signed_ok += x509_signed_by(&c, &c);
            }
        }
        used += n;
    }
    printf("tlscrypto: the system's roots: %d of %d read, %d of %d SHA-2 self-signatures right\n",
           read_ok, blocks, signed_ok, sha2);
}

int main(void)
{
    test_symmetric();
    test_signatures();
    test_threads();
    test_chain();
    test_roots();
    printf("tlscrypto: %s\n", failures ? "FAILED" : "all ok");
    return failures != 0;
}
