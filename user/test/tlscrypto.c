static int nibble(char c)
{
    return c <= '9' ? c - '0' : (c | 32) - 'a' + 10;
}

static size_t hex(const char *s, uint8_t *out)
{
    size_t n = 0;
    for (; s[0] && s[1]; s += 2)
        out[n++] = (uint8_t)(nibble(s[0]) << 4 | nibble(s[1]));
    return n;
}

static int same(const uint8_t *got, const char *want)
{
    uint8_t w[128];
    size_t n = hex(want, w);
    return memcmp(got, w, n) == 0;
}

