/*
 * (37g-5c-2) The registers of display pipe 0's path, as dword indexes in
 * BAR 5 (segment base added), for the snapshot amdgpu keeps over a sleep
 * (`displays sleep`), block by block in the order the pipe runs (clocks,
 * the hub, HUBP, DPP, MPC, OPP, OTG, ODM, VTG, DPG, OPPBUF, the output
 * gamma, pipe 0's power domains, DIG; then the memory window, the panel,
 * its HPD and AUX, the PHY; and the GPU's memory hub, as Linux's
 * mmhub_v1_0.c sets it up on a resume). (37g-5d) Read only, never put
 * back: the display's host VM (DCHVM), VGA mode, the memory hub's FB
 * offset. (37g-6) Two lists: DCN 2.1 (Cezanne: dcn21_) and DCN 1.0 (Raven,
 * Picasso: dcn10_). The names and places are Linux's dcn_2_1_0_offset.h,
 * dpcs_2_1_0_offset.h, dcn_1_0_offset.h and mmhub_1_0_offset.h (facts),
 * the lists made from them by a scratch script; left out: data ports,
 * look-up tables, counters, audio, HDMI, CRC and debug registers (a read
 * of a data port moves its index).
 */
