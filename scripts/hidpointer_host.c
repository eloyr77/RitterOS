static void report(const char *name, const struct hid_pointer *p, const uint8_t *r, size_t n)
{
    int dx, dy, wheel, pan;
    uint8_t buttons;
    printf("%s", name);
    for (size_t i = 0; i < n; i++)
        printf(" %02x", r[i]);
    if (hid_pointer_read(p, r, n, &dx, &dy, &wheel, &pan, &buttons))
        printf(": dx %d dy %d wheel %d pan %d buttons %d\n", dx, dy, wheel, pan, buttons);
    else
        printf(": not its report\n");
}

static bool layout(const char *name, const uint8_t *d, size_t n, struct hid_pointer *p)
{
    struct hid_field fields[160];
    int count = hid_parse(d, n, fields, 160);
    if (count <= 0 || !hid_pointer_find(fields, count, p)) {
        printf("%s: %d fields, no relative pointer\n", name, count);
        return false;
    }
    printf("%s: report %d, %zu bytes, x %u bits at %u, y %u at %u, wheel %u at %u, pan %u at %u, "
           "buttons %u %u %u\n", name, p->report_id, p->bytes, p->x.size, p->x.bit, p->y.size,
           p->y.bit, p->wheel.size, p->wheel.bit, p->pan.size, p->pan.bit, p->button[0].size,
           p->button[1].size, p->button[2].size);
    return true;
}

int main(void)
{
    struct hid_pointer p;
    if (layout("qemu", qemu, sizeof(qemu), &p)) {
        report("qemu", &p, (const uint8_t[]){ 0x01, 0xfd, 0x03, 0x01 }, 4);
        report("qemu", &p, (const uint8_t[]){ 0x06, 0x7f, 0x81, 0xff }, 4);
        report("qemu", &p, (const uint8_t[]){ 0x01, 0x02 }, 2);
    }
    if (layout("ids", ids, sizeof(ids), &p)) {
        report("ids", &p, (const uint8_t[]){ 0x02, 0x05, 0x00, 0xfb, 0xcf, 0x12, 0xff, 0x02 }, 8);
        report("ids", &p, (const uint8_t[]){ 0x02, 0x00, 0x80, 0x01, 0x10, 0x80, 0x00, 0xfe }, 8);
        report("ids", &p, (const uint8_t[]){ 0x03, 0xe9, 0x00 }, 3);
        report("ids", &p, (const uint8_t[]){ 0x02, 0x01, 0x00 }, 3);
    }
    if (layout("extended", extended, sizeof(extended), &p))
        report("extended", &p, (const uint8_t[]){ 0x02, 0x10, 0xf0, 0x78, 0x00, 0xfe }, 6);
    layout("absolute", absolute, sizeof(absolute), &p);
    return 0;
}
